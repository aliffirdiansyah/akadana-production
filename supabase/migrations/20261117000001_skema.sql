-- Skema undangan digital Inviora.
-- Semua tabel memakai RLS tanpa policy: anon/authenticated key tidak bisa membaca atau menulis langsung.
-- Akses hanya dari server Next.js (route handler / server component) dengan service role key,
-- sehingga aturan bisnis dan validasi tetap di satu tempat (src/lib/undangan).
-- Akun pengguna memakai Supabase Auth (auth.users), tanpa tabel pengguna sendiri.

-- ============================================================
-- Template
-- dokumen_awal: dokumen JSON (versi, meta, section[id, tipe, varian, tampil, isi]),
-- divalidasi di src/lib/undangan/dokumen.ts. Template aktif dengan urutan terendah = gratis.
-- ============================================================
CREATE TABLE public.m_template (
    kode         varchar(30) PRIMARY KEY,
    nama         varchar(100) NOT NULL,
    dokumen_awal jsonb NOT NULL,
    urutan       integer NOT NULL DEFAULT 0,
    aktif        boolean NOT NULL DEFAULT true
);

-- ============================================================
-- Undangan
-- status: 1 = Draf (foto sedang diunggah), 2 = Terbit, 3 = Arsip (lihat EStatusUndangan di src/lib/undangan/konstanta.ts)
-- kode_edit_hash: SHA-256 (hex) kode edit yang hanya ditampilkan sekali ke pembuat.
-- pemilik_id: pengguna yang login saat membuat, NULL untuk tamu tanpa akun.
-- ============================================================
CREATE TABLE public.t_undangan (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug           varchar(60) NOT NULL,
    kode_edit_hash varchar(64) NOT NULL,
    template_kode  varchar(30) NOT NULL REFERENCES public.m_template (kode),
    dokumen        jsonb NOT NULL,
    status         integer NOT NULL,
    pemilik_id     uuid REFERENCES auth.users (id) ON DELETE SET NULL,
    ins_date       timestamptz NOT NULL DEFAULT now(),
    upd_date       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_undangan_slug UNIQUE (slug),
    CONSTRAINT ck_undangan_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_undangan_status CHECK (status IN (1, 2, 3))
);
CREATE INDEX ix_undangan_pemilik ON public.t_undangan (pemilik_id, ins_date DESC) WHERE pemilik_id IS NOT NULL;

-- Data pribadi tamu (nama): hanya untuk pemilik undangan
CREATE TABLE public.t_rsvp (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    undangan_id bigint NOT NULL REFERENCES public.t_undangan (id) ON DELETE CASCADE,
    nama        varchar(80) NOT NULL,
    hadir       boolean NOT NULL,
    jumlah      integer NOT NULL,
    ins_date    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_rsvp_jumlah CHECK (jumlah BETWEEN 0 AND 10)
);
CREATE INDEX ix_rsvp_undangan ON public.t_rsvp (undangan_id, ins_date);

CREATE TABLE public.t_ucapan (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    undangan_id   bigint NOT NULL REFERENCES public.t_undangan (id) ON DELETE CASCADE,
    nama          varchar(80) NOT NULL,
    pesan         varchar(500) NOT NULL,
    disembunyikan boolean NOT NULL DEFAULT false,
    ins_date      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_ucapan_undangan ON public.t_ucapan (undangan_id, ins_date DESC);

-- Foto mempelai dan galeri. Isi file ada di Supabase Storage (bucket undangan-foto), path = {slug}/{kunci}.jpg.
-- kunci: 32 karakter hex acak, tidak pernah id.
CREATE TABLE public.t_undangan_foto (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    undangan_id bigint NOT NULL REFERENCES public.t_undangan (id) ON DELETE CASCADE,
    kunci       varchar(32) NOT NULL,
    path        varchar(120) NOT NULL,
    ins_date    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_undangan_foto_kunci UNIQUE (kunci)
);
CREATE INDEX ix_undangan_foto_undangan ON public.t_undangan_foto (undangan_id);

-- Data pribadi tamu (nama): hanya untuk pemilik undangan, tidak tampil di halaman publik
CREATE TABLE public.t_undangan_tamu (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    undangan_id bigint NOT NULL REFERENCES public.t_undangan (id) ON DELETE CASCADE,
    nama        varchar(60) NOT NULL,
    ins_date    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_undangan_tamu_undangan ON public.t_undangan_tamu (undangan_id);

ALTER TABLE public.m_template      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_undangan      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_rsvp          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_ucapan        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_undangan_foto ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_undangan_tamu ENABLE ROW LEVEL SECURITY;

-- ============================================================
-- Storage: foto undangan
-- Publik untuk dibaca (halaman undangan dibuka tanpa login, alamat foto berisi kunci acak).
-- Unggah hanya lewat signed upload URL dari server. Batas ukuran dan tipe dipaksa bucket.
-- ============================================================
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('undangan-foto', 'undangan-foto', true, 2097152, ARRAY['image/jpeg', 'image/png', 'image/webp'])
ON CONFLICT (id) DO UPDATE
SET public = EXCLUDED.public, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;
